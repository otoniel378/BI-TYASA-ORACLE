"""
scripts/setup_proveedores_oracle.py — Crea la tabla de proveedores reales por
material de la página Rutas y puertos (pestaña Proveedores,
mercado_rutas/proveedores.py). La app escribe en ella al registrar o quitar un
proveedor (baja lógica con ACTIVO = 0).

Uso:
    python scripts/setup_proveedores_oracle.py
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import oracledb
from dotenv import load_dotenv

load_dotenv()

TABLES_DDL = {
    "GOLD_PROVEEDORES_MATERIALES": """
        CREATE TABLE ADMIN.GOLD_PROVEEDORES_MATERIALES (
            ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            MATERIAL          VARCHAR2(30)   NOT NULL,
            PROVEEDOR         VARCHAR2(200)  NOT NULL,
            PAIS_ISO          VARCHAR2(3)    NOT NULL,
            RUTA_ID           VARCHAR2(80),
            VOLUMEN_TON_ANIO  NUMBER(12,2),
            NOTAS             VARCHAR2(1000),
            CREADO_POR        VARCHAR2(60),
            CREADO_EN         TIMESTAMP DEFAULT SYSTIMESTAMP,
            ACTIVO            NUMBER(1) DEFAULT 1 NOT NULL
        )
    """,
}


def get_conn() -> oracledb.Connection:
    wallet_dir = os.environ.get("ORACLE_WALLET_DIR", "")
    params = {
        "user":     os.environ.get("ORACLE_USER", "ADMIN"),
        "password": os.environ.get("ORACLE_PASSWORD", ""),
        "dsn":      os.environ.get("ORACLE_DSN", ""),
    }
    if wallet_dir:
        params["config_dir"]      = wallet_dir
        params["wallet_location"] = wallet_dir
        wallet_pw = os.environ.get("ORACLE_WALLET_PASSWORD", "")
        if wallet_pw:
            params["wallet_password"] = wallet_pw
    return oracledb.connect(**params)


def create_tables(recreate: bool = False):
    conn = get_conn()
    cursor = conn.cursor()
    try:
        for name, ddl in TABLES_DDL.items():
            if recreate:
                try:
                    cursor.execute(f"DROP TABLE ADMIN.{name}")
                except oracledb.DatabaseError:
                    pass
            try:
                cursor.execute(ddl.strip())
                conn.commit()
                print(f"  CREATE {name}")
            except oracledb.DatabaseError as e:
                if "ORA-00955" in str(e):
                    print(f"  {name} ya existe, se omite")
                else:
                    raise
    finally:
        cursor.close()
        conn.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--recreate", action="store_true", help="Elimina y re-crea la tabla (borra los proveedores)")
    args = parser.parse_args()
    print("Conectando a Oracle ADW...")
    create_tables(recreate=args.recreate)
    print("\nSetup de proveedores completado.")
